export function getLocalizedScenario(
  scenario: ScenarioQuest,
  lang: SupportedLang
): {
  title: string;
  tagline: string;
  description: string;
  locationName: string;
  npcRole: string;
  greetingText: string;
} {
  const data = SCENARIO_TRANSLATIONS_MAP[scenario.id]?.[lang];
  return {
    title: data?.title ?? scenario.title,
    tagline: data?.tagline ?? scenario.tagline,
    description: data?.description ?? scenario.description,
    locationName: data?.locationName ?? scenario.locationName,
    npcRole: data?.npcRole ?? scenario.npc.role,
    greetingText: data?.greetingText ?? scenario.npc.greetingEnglish,
  };
}

export function getLocalizedTask(
  task: QuestTask,
  lang: SupportedLang
): {
  title: string;
  situation: string;
  objective: string;
  culturalTip: string;
  meaning: string;
} {
  const data = TASK_TRANSLATIONS_MAP[task.id]?.[lang];
  const meaning = task.targetPhrase.translations[lang] ?? task.targetPhrase.english;

  return {
    title: data?.title ?? task.title,
    situation: data?.situation ?? task.situation,
    objective: data?.objective ?? task.objective,
    culturalTip: data?.culturalTip ?? task.culturalTip,
    meaning,
  };
}

export function getLocalizedLevel(
  level: GamificationLevel,
  lang: SupportedLang
): { title: string; description: string } {
  const data = LEVEL_TRANSLATIONS_MAP[level.level]?.[lang];
  return {
    title: data?.title ?? level.title,
    description: data?.description ?? level.description,
  };
}
